// Command tco turns finops/onprem-tco.yaml into OpenCost custom pricing values.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"math"
	"os"

	"gopkg.in/yaml.v3"
)

const hoursPerMonth = 730

type Hypervisor struct {
	Name               string  `yaml:"name"`
	PurchaseEUR        float64 `yaml:"purchase_eur"`
	AmortizationMonths float64 `yaml:"amortization_months"`
}

type TCO struct {
	Currency      string       `yaml:"currency"`
	EffectiveFrom string       `yaml:"effective_from"`
	Hypervisors   []Hypervisor `yaml:"hypervisors"`
	Power         struct {
		MeasuredWatts float64 `yaml:"measured_watts"`
		EURPerKWhTTC  float64 `yaml:"electricity_eur_per_kwh_ttc"`
	} `yaml:"power"`
	Network struct {
		InternetEURPerMonth float64 `yaml:"internet_eur_per_month"`
		PlatformShare       float64 `yaml:"platform_share"`
	} `yaml:"network"`
	Cluster struct {
		VCPU       float64 `yaml:"vcpu"`
		RAMGiB     float64 `yaml:"ram_gib"`
		StorageGiB float64 `yaml:"storage_gib"`
		Split      struct {
			CPU     float64 `yaml:"cpu"`
			RAM     float64 `yaml:"ram"`
			Storage float64 `yaml:"storage"`
		} `yaml:"split"`
	} `yaml:"cluster"`
}

type HourlyPrices struct {
	ClusterEURPerHour float64
	CPUPerVCPUHour    float64
	RAMPerGiBHour     float64
	StoragePerGiBHour float64
}

func (t TCO) validate() error {
	c := t.Cluster
	if c.VCPU <= 0 || c.RAMGiB <= 0 || c.StorageGiB <= 0 {
		return errors.New("cluster vcpu, ram_gib and storage_gib must be positive")
	}
	if sum := c.Split.CPU + c.Split.RAM + c.Split.Storage; math.Abs(sum-1) > 1e-9 {
		return fmt.Errorf("cluster split must sum to 1, got %.4f", sum)
	}
	for _, h := range t.Hypervisors {
		if h.PurchaseEUR > 0 && h.AmortizationMonths <= 0 {
			return fmt.Errorf("hypervisor %s: amortization_months must be positive", h.Name)
		}
	}
	return nil
}

func (t TCO) Prices() (HourlyPrices, error) {
	if err := t.validate(); err != nil {
		return HourlyPrices{}, err
	}
	energy := t.Power.MeasuredWatts / 1000 * t.Power.EURPerKWhTTC
	var amortization float64
	for _, h := range t.Hypervisors {
		if h.PurchaseEUR > 0 {
			amortization += h.PurchaseEUR / (h.AmortizationMonths * hoursPerMonth)
		}
	}
	network := t.Network.InternetEURPerMonth * t.Network.PlatformShare / hoursPerMonth
	hourly := energy + amortization + network

	c := t.Cluster
	return HourlyPrices{
		ClusterEURPerHour: hourly,
		CPUPerVCPUHour:    hourly * c.Split.CPU / c.VCPU,
		RAMPerGiBHour:     hourly * c.Split.RAM / c.RAMGiB,
		StoragePerGiBHour: hourly * c.Split.Storage / c.StorageGiB,
	}, nil
}

// OpenCost's custom provider reads every price as a string, per hour.
func render(t TCO, p HourlyPrices) ([]byte, error) {
	price := func(v float64) string { return fmt.Sprintf("%.8f", v) }
	values := map[string]any{
		"opencost": map[string]any{
			"customPricing": map[string]any{
				"enabled":  true,
				"provider": "custom",
				"costModel": map[string]any{
					"description":           fmt.Sprintf("CNP on-prem TCO effective %s, %.4f %s/h for the cluster", t.EffectiveFrom, p.ClusterEURPerHour, t.Currency),
					"CPU":                   price(p.CPUPerVCPUHour),
					"spotCPU":               price(p.CPUPerVCPUHour),
					"RAM":                   price(p.RAMPerGiBHour),
					"spotRAM":               price(p.RAMPerGiBHour),
					"GPU":                   price(0),
					"storage":               price(p.StoragePerGiBHour),
					"zoneNetworkEgress":     price(0),
					"regionNetworkEgress":   price(0),
					"internetNetworkEgress": price(0),
				},
			},
		},
	}
	var buf bytes.Buffer
	buf.WriteString("# Generated by `go -C finops run ./tco` from finops/onprem-tco.yaml. Do not edit.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(values); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func run(tcoPath, outPath string, check bool) error {
	raw, err := os.ReadFile(tcoPath)
	if err != nil {
		return fmt.Errorf("read tco: %w", err)
	}
	var t TCO
	if err := yaml.Unmarshal(raw, &t); err != nil {
		return fmt.Errorf("parse tco: %w", err)
	}
	prices, err := t.Prices()
	if err != nil {
		return fmt.Errorf("compute prices: %w", err)
	}
	out, err := render(t, prices)
	if err != nil {
		return fmt.Errorf("render values: %w", err)
	}
	if check {
		current, err := os.ReadFile(outPath)
		if err != nil {
			return fmt.Errorf("read %s: %w", outPath, err)
		}
		if !bytes.Equal(current, out) {
			return fmt.Errorf("%s is out of date: run `go -C finops run ./tco`", outPath)
		}
		return nil
	}
	return os.WriteFile(outPath, out, 0o644)
}

func main() {
	tcoPath := flag.String("tco", "onprem-tco.yaml", "TCO file")
	outPath := flag.String("out", "../k8s/config/opencost/values-pricing.yaml", "generated OpenCost values")
	check := flag.Bool("check", false, "fail if the generated file is out of date instead of writing it")
	flag.Parse()
	if err := run(*tcoPath, *outPath, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
